type Plan = {
  publishedMs: number;
  category: "database" | "app_sqli";
  flags: Set<Flag>;
};

export function resolveCount(opts: Pick<GenerateOptions, "count" | "scenario">): number {
  if (opts.scenario === "empty") return 0;
  if (opts.count !== undefined) return opts.count;
  return opts.scenario === "large" ? LARGE_COUNT : DEFAULT_COUNT;
}

export function generateDemoData(opts: GenerateOptions): Map<string, unknown> {
  const rng = new Rng(`${opts.seed}:${opts.scenario}`);
  const count = resolveCount(opts);
  const products = opts.watchlist.products.filter((p) => p.enabled);
  const productById = new Map(products.map((p) => [p.id, p]));

  // Data was last updated `updatedHoursAgo` before `now` — the stale scenario is 40h.
  const updatedHoursAgo = opts.scenario === "stale" ? 40 : 3;
  const anchorMs = opts.now.getTime() - updatedHoursAgo * HOUR;
  const anchor = new Date(anchorMs);

  // ---------- 1. plan publication times and forced cases ----------
  const plans: Plan[] = [];
  const fixedHours = [0.2, 0.9, 2.5, 5, 9, 14, 20, 30, 44];
  for (let i = 0; i < count; i++) {
    const ageMs =
      i < fixedHours.length
        ? (fixedHours[i] as number) * HOUR
        : rng.next() ** 1.7 * SPAN_DAYS * DAY + rng.float(0, HOUR);
    plans.push({ publishedMs: anchorMs - ageMs, category: "database", flags: new Set() });
  }
  plans.sort((a, b) => b.publishedMs - a.publishedMs); // newest first
  if (count > 0) {
    // Spread forced cases over CVEs older than ~2 months so KEV due dates and EPSS history exist.
    const start = Math.floor(count * 0.3);
    const stride = Math.max(1, Math.floor((count - start) / (COVERAGE.length + 1)));
    COVERAGE.forEach((flags, k) => {
      const plan = plans[(start + k * stride) % count];
      for (const f of flags) plan?.flags.add(f);
    });
    // A KEV entry with a due date still in the future needs a recent CVE.
    plans[Math.min(3, count - 1)]?.flags.add("kev:future");
    plans[Math.min(3, count - 1)]?.flags.add("sev:CRITICAL");
  }
  if (opts.settings.appSqli && count > 0) {
    const n = Math.max(3, Math.round(count * 0.04));
    for (let i = 0; i < n; i++) {
      plans.push({
        publishedMs: anchorMs - rng.next() ** 1.5 * SPAN_DAYS * DAY,
        category: "app_sqli",
        flags: new Set(),
      });
    }
  }
  // IDs increase with publication time, like real CVE IDs mostly do.
  const ordered = [...plans].sort((a, b) => a.publishedMs - b.publishedMs);
  const idOf = new Map<Plan, string>();
  ordered.forEach((p, i) => {
    idOf.set(p, `CVE-2099-${10001 + i}`);
  });

  // ---------- 2. build records ----------
  const weighted = products
    .filter((p) => p.id !== EMPTY_PRODUCT_ID)
    .map((p) => [p, PRODUCT_WEIGHTS[p.id] ?? 1] as const);
  const drivers = products.filter((p) => p.category === "driver");

  const cves: CveRecord[] = [];
  const epssScores: EpssCurrent["scores"] = {};
  const epssHistory = new Map<string, Map<string, EpssPoint[]>>();
  const epssDate = isoDay(
    opts.scenario === "source-error" ? anchorMs - DAY : anchorMs, // EPSS failed today
  );

  for (const plan of ordered) {
    const id = idOf.get(plan) as string;
    const ctx = {
      rng,
      id,
      plan,
      anchorMs,
      products: weighted,
      drivers,
      productById,
      settings: opts.settings,
    };
    const record =
      plan.category === "app_sqli" ? buildAppSqliRecord(ctx) : buildDatabaseRecord(ctx);

    // EPSS — CVEs younger than a day have no score yet (EPSS publishes daily).
    const ageMs = anchorMs - plan.publishedMs;
    if (ageMs > DAY) {
      const { current, history, events } = buildEpss(ctx, record, epssDate);
      epssScores[id] = current;
      for (const pt of history) {
        const year = pt[0].slice(0, 4);
        let byCve = epssHistory.get(year);
        if (!byCve) {
          byCve = new Map();
          epssHistory.set(year, byCve);
        }
        byCve.set(id, [...(byCve.get(id) ?? []), pt]);
      }
      record.events.push(...events);
    }
    record.events.sort((a, b) =>
      a.detected_at !== b.detected_at ? (a.detected_at < b.detected_at ? -1 : 1) : 0,
    );
    record.lastModified = maxIso([record.published, ...record.events.map((e) => e.detected_at)]);
    if (record.sources.nvd) record.sources.nvd.lastModified = record.lastModified;
    if (record.sources.cvelist) record.sources.cvelist.dateUpdated = record.lastModified;
    cves.push(record);
  }

  // ---------- 3. derived files ----------
  const files = new Map<string, unknown>();
  for (const cve of cves) files.set(`cves/${cve.id.slice(4, 8)}/${cve.id}.json`, cve);

  const epssCurrent: EpssCurrent = {
    notice: NOTICE,
    date: cves.length ? epssDate : null,
    scores: epssScores,
  };
  files.set("epss/current.json", epssCurrent);
  for (const [year, byCve] of epssHistory) {
    const history: EpssHistory = {
      notice: NOTICE,
      year,
      points: Object.fromEntries(byCve),
    };
    files.set(`epss/history/${year}.json`, history);
  }

  const shards = buildIndexShards(cves, NOTICE);
  for (const shard of shards) files.set(`index/${shard.month}.json`, shard);
  for (const shard of buildEventsShards(cves, NOTICE)) {
    files.set(`events/${shard.month}.json`, shard);
  }
  const anchorIso = anchor.toISOString();
  files.set(
    "latest.json",
    buildLatest({
      cves,
      epss: epssCurrent,
      shards,
      count: opts.settings.latestCount,
      generatedAt: anchorIso,
      updatedAt: anchorIso,
      notice: NOTICE,
    }),
  );
  files.set(
    "stats.json",
    buildStats({
      cves,
      productIds: products.map((p) => p.id),
      now: anchor,
      generatedAt: anchorIso,
      notice: NOTICE,
    }),
  );
  const { status, state } = buildStatus(opts.scenario, rng, anchorMs, cves.length);
  files.set("status.json", status);
  files.set("state.json", state);
  return files;
}

