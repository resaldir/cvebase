type Ctx = {
  rng: Rng;
  id: string;
  plan: Plan;
  anchorMs: number;
  products: (readonly [Product, number])[];
  drivers: Product[];
  productById: Map<string, Product>;
  settings: Settings;
};

function flagValue<P extends string>(flags: Set<Flag>, prefix: P): string | undefined {
  for (const f of flags) if (f.startsWith(prefix)) return f.slice(prefix.length);
  return undefined;
}

function buildDatabaseRecord(ctx: Ctx): CveRecord {
  const { rng, plan, id } = ctx;
  const f = plan.flags;
  const ageMs = ctx.anchorMs - plan.publishedMs;
  const minimal = f.has("minimal");

  // Primary product
  let primary: Product;
  if (f.has("match:MEDIUM") && ctx.drivers.length) primary = rng.pick(ctx.drivers);
  else primary = rng.weighted(ctx.products);

  // Severity and CVSS
  let sev: SevTarget = (flagValue(f, "sev:") as SevTarget | undefined) ?? pickSeverity(rng, ageMs);
  if (minimal) sev = "UNSCORED";
  const kind: CvssKind =
    (flagValue(f, "cvss:") as CvssKind | undefined) ??
    rng.weighted([
      ["v31", 45],
      ["v40", 15],
      ["both", 40],
    ] as const);
  const cvss = buildCvss(rng, sev, kind);
  const severity: Severity = cvss.v40?.severity ?? cvss.v31?.severity ?? "UNSCORED";

  // Matches
  const matches: Match[] = [buildMatch(ctx, primary, f, true)];
  if (f.has("multi") || (!minimal && rng.chance(0.08))) {
    const family = (FAMILIES[primary.id] ?? []).filter((pid) => ctx.productById.has(pid));
    const extras = family.length
      ? rng.sample(family, rng.int(1, Math.min(2, family.length)))
      : [rng.weighted(ctx.products).id].filter((pid) => pid !== primary.id);
    for (const pid of extras) {
      const p = ctx.productById.get(pid);
      if (p && pid !== "pgbackrest") matches.push(buildMatch(ctx, p, new Set(), false));
    }
  }
  matches.sort((a, b) => a.productId.localeCompare(b.productId));

  // Description
  const [issue, cweId, cweName] = rng.pick(ISSUES);
  const component = rng.pick(COMPONENTS);
  const actor = rng.pick(ACTORS);
  const impact = rng.pick(IMPACTS);
  const productNames = matches.map((m) => ctx.productById.get(m.productId)?.name ?? m.productId);
  let description: string;
  if (minimal) {
    description = `[DEMO] Unspecified vulnerability in ${primary.name}.`;
  } else {
    description = `[DEMO] ${article(issue)} ${issue} in the ${component} component of ${joinNames(
      productNames,
    )} allows ${actor} to ${impact}.`;
    if (f.has("long-desc")) description += longTail(rng, primary.name, component);
    else if (rng.chance(0.4))
      description += ` Successful exploitation requires ${rng.pick([
        "a non-default configuration",
        "network access to the server port",
        "the CREATE privilege",
        "a crafted query",
        "the extension to be installed",
      ])}.`;
  }
  const summary = oneLine(description);

  // References
  const refCount = minimal ? 0 : f.has("long-refs") ? rng.int(40, 60) : rng.int(1, 6);
  const vendorSlug = slugify(primary.vendor);
  const references = Array.from({ length: refCount }, (_, i) => ({
    url:
      i === 0
        ? `https://example.com/demo/${vendorSlug}/advisories/${id.toLowerCase()}`
        : `https://example.com/demo/${rng.pick(["lists", "bugs", "commits", "blog", "notes"])}/${id.toLowerCase()}-${i}`,
    source: rng.pick(["demo-cna@example.com", "nvd@example.com", null]),
    tags: rng.sample(REF_TAGS, rng.int(0, 2)).sort(),
  }));
  const vendorAdvisories =
    !minimal && rng.chance(0.5)
      ? [
          {
            title: `${primary.vendor} security advisory for ${id} (demo)`,
            url: `https://example.com/demo/${vendorSlug}/security/${id.toLowerCase()}`,
          },
        ]
      : [];

  // KEV
  const kevFlag = flagValue(f, "kev:");
  const kevChance =
    severity === "CRITICAL" ? 0.22 : severity === "HIGH" ? 0.05 : severity === "MEDIUM" ? 0.01 : 0;
  const isKev =
    kevFlag !== undefined || (severity !== "UNSCORED" && ageMs > 3 * DAY && rng.chance(kevChance));
  let kev: CveRecord["kev"] = null;
  if (isKev) {
    const addedMs =
      kevFlag === "future"
        ? Math.min(plan.publishedMs + 2 * HOUR, ctx.anchorMs)
        : kevFlag === "ransomware-past"
          ? Math.min(plan.publishedMs + rng.int(1, 10) * DAY, ctx.anchorMs - 22 * DAY)
          : Math.min(plan.publishedMs + rng.int(1, 45) * DAY, ctx.anchorMs - DAY);
    const dateAdded = isoDay(Math.max(addedMs, plan.publishedMs));
    const due = new Date(`${dateAdded}T00:00:00Z`);
    due.setUTCDate(due.getUTCDate() + 21);
    kev = {
      dateAdded,
      dueDate: due.toISOString().slice(0, 10),
      knownRansomwareCampaignUse:
        kevFlag === "ransomware-past"
          ? "Known"
          : kevFlag === "unknown"
            ? "Unknown"
            : rng.chance(0.3)
              ? "Known"
              : "Unknown",
      requiredAction:
        "[DEMO] Apply mitigations per vendor instructions or discontinue use of the product if mitigations are unavailable.",
      vulnerabilityName: `[DEMO] ${primary.vendor} ${primary.name} ${titleCase(issue)} Vulnerability`,
      notes: rng.chance(0.5) ? `https://example.com/demo/kev/${id.toLowerCase()}` : null,
    };
  }

  // Events
  const events: ChangeEvent[] = [];
  const at = (ms: number) => new Date(Math.min(ms, ctx.anchorMs)).toISOString();
  const published = new Date(plan.publishedMs).toISOString();
  const primaryScore = cvss.v40?.score ?? cvss.v31?.score ?? null;
  const scoreChanged =
    f.has("event:score-changed") ||
    (severity !== "UNSCORED" && ageMs > 4 * DAY && rng.chance(0.18));
  events.push({
    cve_id: id,
    type: "published",
    old: null,
    new: scoreChanged ? "UNSCORED" : severity,
    detected_at: at(plan.publishedMs + rng.int(5, 90) * 60_000),
  });
  if (scoreChanged && primaryScore !== null) {
    const t = plan.publishedMs + rng.float(1.5, 4) * DAY;
    events.push({
      cve_id: id,
      type: "severity_changed",
      old: "UNSCORED",
      new: severity,
      detected_at: at(t),
    });
    if (f.has("event:score-changed") || rng.chance(0.4)) {
      const old = Math.max(0.1, Math.round((primaryScore - rng.float(0.3, 1.2)) * 10) / 10);
      events.push({
        cve_id: id,
        type: "cvss_changed",
        old,
        new: primaryScore,
        detected_at: at(t + rng.float(3, 20) * DAY),
      });
      if (severityFromScore(old) !== severity) {
        events.push({
          cve_id: id,
          type: "severity_changed",
          old: severityFromScore(old),
          new: severity,
          detected_at: at(t + rng.float(20.1, 21) * DAY),
        });
      }
    }
  }
  if (kev) {
    events.push({
      cve_id: id,
      type: "kev_added",
      old: null,
      new: kev.dateAdded,
      detected_at: at(Math.max(Date.parse(`${kev.dateAdded}T15:00:00Z`), plan.publishedMs + HOUR)),
    });
  }
  const upgradable = matches.find((m) => m.confidence === "HIGH");
  if (upgradable && (f.has("event:match-upgraded") || (ageMs > 5 * DAY && rng.chance(0.06)))) {
    events.push({
      cve_id: id,
      type: "match_upgraded",
      old: "LOW",
      new: "HIGH",
      product_id: upgradable.productId,
      detected_at: at(plan.publishedMs + rng.float(1, 5) * DAY),
    });
  }
  if (f.has("event:match-upgraded") && !upgradable) {
    // Ensure the coverage case even if all matches ended up MEDIUM/LOW.
    const m = matches[0] as Match;
    m.confidence = "HIGH";
    m.method = "nvd_cpe";
    events.push({
      cve_id: id,
      type: "match_upgraded",
      old: "LOW",
      new: "HIGH",
      product_id: m.productId,
      detected_at: at(plan.publishedMs + 2 * DAY),
    });
  }

  const unscored = severity === "UNSCORED";
  const vulnStatus = unscored
    ? rng.pick(["Awaiting Analysis", "Received", "Undergoing Analysis"])
    : rng.chance(0.8)
      ? "Analyzed"
      : "Modified";
  const onlyInCvelist = unscored && ageMs < 2 * DAY && rng.chance(0.6);

  return {
    notice: NOTICE,
    id,
    published,
    lastModified: published,
    vulnStatus: onlyInCvelist ? "Received" : vulnStatus,
    category: "database",
    description,
    summary,
    severity,
    cvss,
    cwes: minimal
      ? []
      : rng.chance(0.08)
        ? [{ id: "NVD-CWE-noinfo", name: null }]
        : [{ id: cweId, name: cweName }],
    references,
    vendorAdvisories,
    kev,
    matches,
    events,
    sources: {
      nvd: onlyInCvelist ? null : { vulnStatus, lastModified: published },
      cvelist: {
        assigner: `${vendorSlug}-demo-cna`,
        datePublished: published,
        dateUpdated: published,
      },
    },
  };
}

function buildAppSqliRecord(ctx: Ctx): CveRecord {
  const { rng, id, plan } = ctx;
  const app = `${rng.pick(["Acme", "Widget", "Sample", "Foo", "Contoso"])} ${rng.pick([
    "Gallery",
    "Booking",
    "Forms",
    "Shop",
    "Survey",
  ])}`;
  const description = `[DEMO] SQL injection in the ${app} plugin for ExampleCMS allows an unauthenticated attacker to execute arbitrary SQL commands via the "${rng.pick(["id", "sort", "q", "category"])}" parameter. This is a web application flaw, not a database product vulnerability.`;
  const sev = rng.weighted([
    ["CRITICAL", 2],
    ["HIGH", 5],
    ["MEDIUM", 3],
  ] as const);
  const cvss = buildCvss(rng, sev, "v31");
  const published = new Date(plan.publishedMs).toISOString();
  return {
    notice: NOTICE,
    id,
    published,
    lastModified: published,
    vulnStatus: "Analyzed",
    category: "app_sqli",
    description,
    summary: oneLine(description),
    severity: cvss.v31?.severity ?? "UNSCORED",
    cvss,
    cwes: [
      { id: "CWE-89", name: "Improper Neutralization of Special Elements used in an SQL Command" },
    ],
    references: [
      { url: `https://example.com/demo/appsqli/${id.toLowerCase()}`, source: null, tags: [] },
    ],
    vendorAdvisories: [],
    kev: null,
    matches: [],
    events: [
      {
        cve_id: id,
        type: "published",
        old: null,
        new: cvss.v31?.severity ?? "UNSCORED",
        detected_at: new Date(Math.min(plan.publishedMs + 30 * 60_000, ctx.anchorMs)).toISOString(),
      },
    ],
    sources: {
      nvd: { vulnStatus: "Analyzed", lastModified: published },
      cvelist: { assigner: "demo-cna", datePublished: published, dateUpdated: published },
    },
  };
}

function pickSeverity(rng: Rng, ageMs: number): SevTarget {
  // Brand-new CVEs are often still awaiting NVD analysis.
  if (ageMs < 2 * DAY && rng.chance(0.45)) return "UNSCORED";
  return rng.weighted([
    ["CRITICAL", 7],
    ["HIGH", 35],
    ["MEDIUM", 43],
    ["LOW", 7],
    ["UNSCORED", 8],
  ] as const);
}

const V31 = {
  AV: ["N", "N", "N", "A", "L", "P"],
  AC: ["L", "L", "H"],
  PR: ["N", "L", "L", "H"],
  UI: ["N", "N", "R"],
  S: ["U", "U", "U", "C"],
  CIA: ["H", "L", "N"],
} as const;

function buildCvss(rng: Rng, sev: SevTarget, kind: CvssKind): CveRecord["cvss"] {
  if (sev === "UNSCORED") return { v31: null, v40: null };
  let v31: CveRecord["cvss"]["v31"] = null;
  let v40: CveRecord["cvss"]["v40"] = null;
  if (kind !== "v40") {
    let vector = "";
    let score = 0;
    for (let attempt = 0; attempt < 400; attempt++) {
      const cia =
        sev === "NONE"
          ? ["N", "N", "N"]
          : [rng.pick(V31.CIA), rng.pick(V31.CIA), rng.pick(V31.CIA)];
      vector = `CVSS:3.1/AV:${rng.pick(V31.AV)}/AC:${rng.pick(V31.AC)}/PR:${rng.pick(V31.PR)}/UI:${rng.pick(V31.UI)}/S:${rng.pick(V31.S)}/C:${cia[0]}/I:${cia[1]}/A:${cia[2]}`;
      score = cvss31BaseScore(vector);
      if (severityFromScore(score) === sev) break;
    }
    v31 = { score, vector, severity: severityFromScore(score), source: "nvd@example.com" };
  }
  if (kind !== "v31") {
    // v4.0 scoring uses lookup tables; the demo picks a score within the same band.
    const band: Record<Exclude<Severity, "UNSCORED">, [number, number]> = {
      NONE: [0, 0],
      LOW: [1, 3.9],
      MEDIUM: [4, 6.9],
      HIGH: [7, 8.9],
      CRITICAL: [9, 10],
    };
    const [lo, hi] = band[sev];
    const score = Math.round(rng.float(lo, hi) * 10) / 10;
    const imp = () => (sev === "NONE" ? "N" : rng.pick(V31.CIA));
    const vector = `CVSS:4.0/AV:${rng.pick(V31.AV)}/AC:${rng.pick(["L", "H"])}/AT:${rng.pick(["N", "P"])}/PR:${rng.pick(["N", "L", "H"])}/UI:${rng.pick(["N", "P", "A"])}/VC:${imp()}/VI:${imp()}/VA:${imp()}/SC:${rng.pick(["N", "L"])}/SI:${rng.pick(["N", "L"])}/SA:${rng.pick(["N", "L"])}`;
    v40 = { score, vector, severity: severityFromScore(score), source: "demo-cna@example.com" };
  }
  return { v31, v40 };
}

function buildMatch(ctx: Ctx, product: Product, flags: Set<Flag>, primary: boolean): Match {
  const { rng } = ctx;
  let confidence: Confidence;
  let method: MatchMethod;
  if (flags.has("match:LOW")) confidence = "LOW";
  else if (flags.has("match:MEDIUM")) confidence = "MEDIUM";
  else if (product.category === "driver" && product.packages.length && rng.chance(0.5))
    confidence = "MEDIUM";
  else confidence = rng.chance(primary ? 0.1 : 0.15) ? "LOW" : "HIGH";

  if (confidence === "LOW") method = "keyword";
  else if (confidence === "MEDIUM") method = "ghsa_package";
  else method = rng.chance(0.7) ? "nvd_cpe" : "cna_affected";

  const cpe = product.cpes[0];
  const pkg = product.packages[0];
  const evidence =
    method === "nvd_cpe"
      ? `cpe:2.3:a:${cpe?.vendor}:${cpe?.product}:*`
      : method === "cna_affected"
        ? `${product.vendor} / ${product.name}`
        : method === "ghsa_package"
          ? `${pkg?.ecosystem ?? "maven"}:${pkg?.name ?? product.id}`
          : `"${product.aliases[0] ?? product.name}" in description`;

  const wantRanges = flags.has("ranges")
    ? true
    : flags.has("no-ranges") || flags.has("minimal")
      ? false
      : method !== "keyword" && rng.chance(0.75);
  return {
    productId: product.id,
    method,
    confidence,
    affected: wantRanges ? buildRanges(rng) : [],
    evidence,
  };
}

function buildRanges(rng: Rng): VersionRange[] {
  const out: VersionRange[] = [];
  const n = rng.int(1, 3);
  let major = rng.int(1, 16);
  for (let i = 0; i < n; i++) {
    const minor = rng.int(0, 9);
    const fixed = rng.int(2, 40);
    const shape = rng.int(0, 3);
    if (shape === 0) out.push({ version: `${major}.${minor}.${rng.int(0, fixed)}` });
    else if (shape === 1)
      out.push({
        versionStartIncluding: `${major}.${minor}.0`,
        versionEndExcluding: `${major}.${minor}.${fixed}`,
      });
    else if (shape === 2) out.push({ versionEndIncluding: `${major}.${minor}.${fixed}` });
    else
      out.push({
        versionStartExcluding: `${major}.0`,
        versionEndExcluding: `${major}.${minor + 1}`,
      });
    major += rng.int(1, 2);
  }
  return out;
}

/** Map EPSS score to an approximate percentile (monotone, piecewise in log space). */
export function approxPercentile(score: number): number {
  const table: [number, number][] = [
    [-4.5, 0],
    [-3, 0.2],
    [-2.3, 0.6],
    [-2, 0.78],
    [-1, 0.94],
    [-0.3, 0.987],
    [0, 1],
  ];
  const x = Math.log10(Math.max(score, 10 ** -4.5));
  for (let i = 1; i < table.length; i++) {
    const [x0, y0] = table[i - 1] as [number, number];
    const [x1, y1] = table[i] as [number, number];
    if (x <= x1) return round5(y0 + ((x - x0) / (x1 - x0)) * (y1 - y0));
  }
  return 1;
}

function buildEpss(
  ctx: Ctx,
  record: CveRecord,
  epssDate: string,
): {
  current: { epss: number; percentile: number; date: string };
  history: EpssPoint[];
  events: ChangeEvent[];
} {
  const { rng, plan } = ctx;
  const f = plan.flags;
  let final: number;
  let start: number;
  if (f.has("epss:high")) {
    final = rng.float(0.92, 0.975);
    start = rng.float(0.02, 0.2);
  } else if (f.has("epss:low")) {
    final = rng.float(0.0002, 0.0006);
    start = final;
  } else if (f.has("epss:cross")) {
    final = rng.float(0.55, 0.8);
    start = rng.float(0.01, 0.05);
  } else if (record.kev) {
    final = rng.float(0.15, 0.97);
    start = final * rng.float(0.05, 0.5);
  } else {
    const sevBoost = record.severity === "CRITICAL" ? 2.5 : record.severity === "HIGH" ? 4 : 6;
    final = 0.0003 + 0.75 * rng.next() ** sevBoost;
    start = rng.chance(0.6) ? final : final * rng.float(0.1, 0.9);
  }
  final = round5(final);
  start = round5(Math.max(0.0001, start));

  // History: a few checkpoints between first score and today, thinned per settings.
  const { minDelta, thresholds } = ctx.settings.epssHistory;
  const firstMs = plan.publishedMs + DAY;
  const lastMs = Date.parse(`${epssDate}T00:00:00Z`);
  const steps = Math.max(1, Math.min(10, Math.floor((lastMs - firstMs) / (14 * DAY))));
  const raw: [number, number][] = [];
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    const noise = i === 0 || i === steps ? 0 : rng.float(-0.03, 0.03);
    const v = Math.min(0.99, Math.max(0.0001, start + (final - start) * t ** 1.5 + noise));
    raw.push([firstMs + (lastMs - firstMs) * t, round5(v)]);
  }
  const history: EpssPoint[] = [];
  const events: ChangeEvent[] = [];
  let prev: number | null = null;
  for (const [ms, v] of raw) {
    const day = isoDay(ms);
    const crosses = prev !== null && thresholds.some((th) => (prev as number) < th !== v < th);
    if (prev === null || Math.abs(v - prev) >= minDelta || crosses) {
      if (history.at(-1)?.[0] !== day) history.push([day, v, approxPercentile(v)]);
      if (prev !== null) {
        for (const [th, type] of [
          [0.1, "epss_crossed_10"],
          [0.5, "epss_crossed_50"],
        ] as const) {
          if (prev < th && v >= th) {
            events.push({
              cve_id: record.id,
              type,
              old: prev,
              new: v,
              detected_at: new Date(Math.min(ms + 6 * HOUR, ctx.anchorMs)).toISOString(),
            });
          }
        }
      }
      prev = v;
    }
  }
  // Only keep a history if the score actually moved.
  const keep = history.length > 1 ? history : [];
  return {
    current: { epss: final, percentile: approxPercentile(final), date: epssDate },
    history: keep,
    events,
  };
}

function buildStatus(
  scenario: Scenario,
  rng: Rng,
  anchorMs: number,
  total: number,
): { status: Status; state: State } {
  const defs: [SourceId, string][] = [
    ["nvd", "NVD CVE API 2.0"],
    ["cvelist", "CVE List V5"],
    ["kev", "CISA KEV catalog"],
    ["epss", "FIRST EPSS API"],
  ];
  const runStart = anchorMs - 4 * 60_000;
  const sources = defs.map(([id, name], i) => {
    const lastRun = new Date(runStart + i * 45_000).toISOString();
    const failed = scenario === "source-error" && id === "epss";
    const n = total === 0 ? 0 : rng.int(1, Math.min(40, total));
    return {
      id,
      name,
      status: failed ? ("error" as const) : ("ok" as const),
      lastRun,
      lastSuccess: failed ? new Date(runStart - DAY + i * 45_000).toISOString() : lastRun,
      durationMs: failed ? 92_000 : rng.int(800, 40_000),
      counts: failed
        ? { fetched: 0, new: 0, updated: 0 }
        : { fetched: id === "epss" ? total : n * 3, new: id === "nvd" ? n : 0, updated: n },
      error: failed
        ? "[DEMO] EPSS API returned HTTP 503 Service Unavailable after 5 retries (last attempt 04:58 UTC)."
        : null,
    };
  });
  const generatedAt = new Date(anchorMs).toISOString();
  return {
    status: {
      notice: NOTICE,
      generated_at: generatedAt,
      lastRun: generatedAt,
      lastSuccessfulRun: generatedAt,
      sources,
    },
    state: {
      notice: NOTICE,
      sources: Object.fromEntries(
        sources.map((s) => [
          s.id,
          {
            cursor: s.lastSuccess,
            lastFetch: s.lastRun,
            etag: s.id === "kev" ? `"demo-${anchorMs.toString(16)}"` : null,
            contentHash: s.id === "kev" ? "sha256:demo" : null,
          },
        ]),
      ) as State["sources"],
    },
  };
}

// ---------------------------------------------------------------------------

function isoDay(ms: number): string {
  return new Date(ms).toISOString().slice(0, 10);
}

function maxIso(values: string[]): string {
  return [...values].sort().at(-1) as string;
}

function round5(x: number): number {
  return Math.round(x * 100000) / 100000;
}

function slugify(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function titleCase(s: string): string {
  return s.replace(/\b\w/g, (c) => c.toUpperCase());
}

function joinNames(names: string[]): string {
  if (names.length <= 1) return names[0] ?? "";
  return `${names.slice(0, -1).join(", ")} and ${names.at(-1)}`;
}

/** First sentence, capped for one-line display. */
export function oneLine(description: string): string {
  const first = description.split(/(?<=\.)\s/)[0] ?? description;
  if (first.length <= 180) return first;
  const cut = first.slice(0, 178);
  return `${cut.slice(0, cut.lastIndexOf(" ")).replace(/[,;:]$/, "")}…`;
}

function longTail(rng: Rng, product: string, component: string): string {
  const paras = [
    ` The issue exists because the ${component} does not correctly validate the length of attacker-supplied data before copying it to a fixed-size buffer.`,
    ` Affected deployments include default installations of ${product} where the vulnerable feature is enabled, as well as builds packaged by third-party distributions that backport the affected code.`,
    " An attacker can trigger the flaw by sending a sequence of specially crafted protocol messages during session setup, before any statement is executed, which makes the vulnerability reachable without completing authentication in some configurations.",
    " The vendor has released fixed versions for all supported release series. Administrators who cannot upgrade immediately should restrict network access to the database port, disable the affected feature where possible, and monitor server logs for unexpected crashes or restarts.",
    " Note that this description is intentionally long to test how the interface wraps and truncates extended advisory text across the feed, the detail page, the RSS output and the JSON API. It does not describe any real product behaviour.",
  ];
  let out = "";
  for (let i = 0; i < 3; i++) for (const p of rng.sample(paras, paras.length)) out += p;
  return out;
}

function article(word: string): string {
  return /^[aeiou]/i.test(word) && !/^u[sn]i/i.test(word) && !/^use/i.test(word) ? "An" : "A";
}
